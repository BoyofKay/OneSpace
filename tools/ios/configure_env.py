#!/usr/bin/env python3
"""Configure the Xcode identity from the same environment used by Dart.

Run from any directory: python3 tools/ios/configure_env.py qa|production
Then build with --dart-define=ONESPACE_ENV=<same environment>.
QA and production must never share a bundle ID, callback or Supabase backend.
"""
from pathlib import Path
import argparse
import plistlib
import sys

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "ios/Flutter/BuildEnvironment.xcconfig"
ENVIRONMENTS = {
    "qa": ("com.onespace.onespace.qa", "onespace-preview", "OneSpace QA"),
    "production": ("com.onespace.onespace", "onespace", "OneSpace"),
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("environment", choices=sorted(ENVIRONMENTS))
    args = parser.parse_args()
    project = (ROOT / "ios/Runner.xcodeproj/project.pbxproj").read_text()
    if 'PRODUCT_BUNDLE_IDENTIFIER = "$(ONESPACE_IOS_BUNDLE_ID)";' not in project:
        sys.exit("Refusing to build: the Xcode Bundle ID is not environment-aware.")
    with (ROOT / "ios/Runner/Info.plist").open("rb") as f:
        info = plistlib.load(f)
    schemes = [
        x for item in info.get("CFBundleURLTypes", [])
        for x in item.get("CFBundleURLSchemes", [])
    ]
    if info.get("OneSpaceEnvironment") != "$(ONESPACE_IOS_ENV)" or \
            "$(ONESPACE_AUTH_SCHEME)" not in schemes or \
            info.get("CFBundleDisplayName") != "$(ONESPACE_APP_DISPLAY_NAME)" or \
            info.get("OneSpaceShareGroup") != "$(ONESPACE_SHARE_GROUP)":
        sys.exit("Refusing to build: the iOS Info.plist environment wiring is missing.")
    bundle, scheme, display = ENVIRONMENTS[args.environment]
    share_group = "group.com.onespace.onespace" + (".qa" if args.environment == "qa" else "")
    CONFIG.write_text(
        "// Generated by tools/ios/configure_env.py. No secrets in this file.\n"
        f"ONESPACE_IOS_ENV = {args.environment}\n"
        f"ONESPACE_IOS_BUNDLE_ID = {bundle}\n"
        f"ONESPACE_AUTH_SCHEME = {scheme}\n"
        f"ONESPACE_APP_DISPLAY_NAME = {display}\n"
        f"ONESPACE_SHARE_GROUP = {share_group}\n"
    )
    print(f"iOS environment: {args.environment} | Bundle ID: {bundle} | URL scheme: {scheme}")


if __name__ == "__main__":
    main()
