#!/usr/bin/env python3
"""27 Nov 2026 (owner decision): one FAQ for the app and the website.

The source is content/faq/*.json in the website repository (BoyofKay/onespace-app).
This writes lib/features/support/faq_content.dart (English and Arabic, items with
"where": both or app). Run it after changing the FAQ:

    python3 tools/faq/sync_faq.py ../onespace-app

It also copies the JSON into tools/faq/source/ so the app repository keeps the exact
source it was generated from (the test checks the Dart file matches that copy).
"""
import json
import shutil
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[2]
OUT = APP / 'lib' / 'features' / 'support' / 'faq_content.dart'
COPY = APP / 'tools' / 'faq' / 'source'


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def render(groups):
    lines = [
        '// GENERATED by tools/faq/sync_faq.py from the shared FAQ (website repo content/faq).',
        '// Do not edit by hand: change the JSON there and run the script again.',
        '',
        '/// One block of an answer: a paragraph, numbered steps or bullet points.',
        'class FaqBlock {',
        '  const FaqBlock(this.kind, this.en, this.ar);',
        "  final String kind; // 'p', 'steps' or 'bullets'",
        '  final List<String> en, ar;',
        '  List<String> lines(bool ar) => ar ? this.ar : en;',
        '}',
        '',
        'class FaqEntry {',
        '  const FaqEntry(this.topicEn, this.topicAr, this.qEn, this.qAr, this.blocks, {this.tutorial});',
        '  final String topicEn, topicAr, qEn, qAr;',
        '  final List<FaqBlock> blocks;',
        "  /// The feature's video tutorial on the website (tutorials.html, at its id), if any.",
        '  final String? tutorial;',
        "  String? get tutorialUrl => tutorial == null ? null : '$faqTutorialUrl#$tutorial';",
        '  String topic(bool ar) => ar ? topicAr : topicEn;',
        '  String q(bool ar) => ar ? qAr : qEn;',
        "  String a(bool ar) => [for (final b in blocks) ...b.lines(ar)].join('\\n');",
        '  String get aEn => a(false);',
        '  String get aAr => a(true);',
        '}',
        '',
        "const faqTutorialUrl = 'https://onespace.live/tutorials.html';",
        '',
        'const faqEntries = <FaqEntry>[',
    ]
    for g in groups:
        for item in g['items']:
            if item.get('where', 'both') not in ('both', 'app'):
                continue
            lines.append(f"  FaqEntry({q(g['title']['en'])}, {q(g['title']['ar'])},")
            lines.append(f"    {q(item['q']['en'])}, {q(item['q']['ar'])}, [")
            for kind, value in item['a']:
                texts = [value] if kind == 'p' else value
                en = ', '.join(q(t['en']) for t in texts)
                ar = ', '.join(q(t['ar']) for t in texts)
                lines.append(f"      FaqBlock('{kind}', [{en}],")
                lines.append(f"        [{ar}]),")
            video = f", tutorial: {q(item['id'])}" if item.get('tutorial') else ''
            lines.append(f"    ]{video}),")
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else APP.parent / 'onespace-app') / 'content' / 'faq'
    files = sorted(src.glob('*.json'))
    if not files:
        sys.exit(f'No FAQ files in {src}')
    COPY.mkdir(parents=True, exist_ok=True)
    for old in COPY.glob('*.json'):
        old.unlink()
    for f in files:
        shutil.copy(f, COPY / f.name)
    groups = [json.loads(f.read_text(encoding='utf-8')) for f in files]
    OUT.write_text(render(groups), encoding='utf-8')
    count = sum(1 for g in groups for i in g['items'] if i.get('where', 'both') in ('both', 'app'))
    print(f'Wrote {OUT.relative_to(APP)}: {count} questions from {len(files)} files')


if __name__ == '__main__':
    main()
