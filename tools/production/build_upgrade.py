#!/usr/bin/env python3
"""Builds the one-shot Production database upgrade from the QA schema files.

QA received supabase/schema/0142..0319 one at a time. Production stopped at
0141. This joins those files, in order, into supabase/production/upgrade.sql,
pointing the worker schedules at the Production project instead of QA, then
appends supabase/production/finalize.sql (existing-data move + checks).

The output runs as ONE transaction: if any statement fails, nothing changes.
Run it only through .github/workflows/prod-db-upgrade.yml.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "supabase" / "schema"
OUT = ROOT / "supabase" / "production" / "upgrade.sql"
FINALIZE = ROOT / "supabase" / "production" / "finalize.sql"
QA_HOST = "ugwrpeduzyzrujkizqfo.supabase.co"
PROD_HOST = "letcgxbnblohhfyeuigz.supabase.co"
UNRECORDED = ROOT / "supabase" / "production" / "unrecorded"
FIRST, LAST = 142, 319
# Files whose number does not match the order QA actually received them in
# (from QA's supabase_migrations history). Value = sort key to use instead.
QA_ORDER = {
    # QA: 0238 personal space rows (=0243), 0239 end shared space (=0244),
    # 0240 today/remember (=0245), and only then the gate on those functions.
    "0242": "0245z",
}

def files():
    """Schema files 0142..0319 plus changes QA received without a schema file
    (supabase/production/unrecorded, named so they sort into place, e.g.
    0150a_ runs after 0150_)."""
    out = []
    for p in list(SCHEMA.glob("*.sql")) + list(UNRECORDED.glob("*.sql")):
        m = re.match(r"(\d{4})[a-z]?_", p.name)
        if m and FIRST <= int(m.group(1)) <= LAST:
            out.append(p)
    return sorted(out, key=lambda p: QA_ORDER.get(p.name[:4], p.name))

def main():
    parts = ["-- GENERATED by tools/production/build_upgrade.py. Do not edit by hand.\n"
             f"-- Production upgrade: supabase/schema {FIRST:04d}..{LAST:04d} + finalize.sql\n"
             "\\set ON_ERROR_STOP on\n"
             "set statement_timeout = 0;\n"
             "set lock_timeout = '30s';\n"]
    fs = files()
    if len({f.name.split("_")[0] for f in fs}) != len(fs):
        sys.exit("two schema files share a number")
    for p in fs:
        sql = p.read_text()
        for bad in (r"^\s*(begin|commit|rollback)\s*;", r"\bconcurrently\b"):
            if re.search(bad, sql, re.I | re.M):
                sys.exit(f"{p.name}: contains a statement that cannot run inside one transaction")
        sql = sql.replace(QA_HOST, PROD_HOST)
        parts.append(f"\n-- >>>>> {p.name}\n{sql.rstrip()}\n;\n")
    parts.append("\n-- >>>>> finalize.sql\n" + FINALIZE.read_text())
    OUT.write_text("".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)} from {len(fs)} files")

if __name__ == "__main__":
    main()
